// Exporta la ESTRUCTURA de la base (sin ninguna fila de datos) a un archivo SQL
// legible: tablas, restricciones, índices, RLS, políticas, permisos, funciones,
// disparadores, vistas y buckets de Storage.
//
//   node tools/exportar-esquema.mjs                       → sql/esquema/esquema-actual.sql
//   node tools/exportar-esquema.mjs ruta/otro-archivo.sql
//
// Solo lee (SELECT sobre el catálogo). Necesita SUPABASE_DB_PASSWORD en .env.
// Existe porque las políticas RLS y funciones como is_admin() se crearon desde el
// panel de Supabase y no están en los archivos numerados de sql/.
import fs from 'fs';
import path from 'path';
import pg from 'pg';

const env = Object.fromEntries(fs.readFileSync('.env', 'utf8').split(/\r?\n/)
  .filter(l => /^[A-Z_]+=/.test(l)).map(l => [l.split('=')[0], l.slice(l.indexOf('=') + 1).trim()]));
const SALIDA = process.argv[2] || 'sql/esquema/esquema-actual.sql';
const ROLES = ['anon', 'authenticated', 'service_role'];

const c = new pg.Client({
  host: 'aws-0-us-west-2.pooler.supabase.com', port: 5432, database: 'postgres',
  user: 'postgres.xqphjvppfgwabfruyjae', password: env.SUPABASE_DB_PASSWORD,
  ssl: { rejectUnauthorized: false }
});
await c.connect();
await c.query('SET default_transaction_read_only = on');
const q = async (sql, params) => (await c.query(sql, params)).rows;
const id = s => '"' + String(s).replace(/"/g, '""') + '"';
const sqlStr = s => s === null || s === undefined ? 'NULL' : "'" + String(s).replace(/'/g, "''") + "'";

const out = [];
const w = (...l) => out.push(...l);
const seccion = t => w('', '-- ' + '='.repeat(70), '-- ' + t, '-- ' + '='.repeat(70), '');

w('-- ESQUEMA DE LA BASE — solo estructura, SIN DATOS',
  '-- Generado: ' + new Date().toISOString().slice(0, 10) + ' con tools/exportar-esquema.mjs',
  '--',
  '-- Úsalo para ENTENDER y AUDITAR la base (quién puede leer o escribir qué) y como',
  '-- punto de partida para reconstruirla en un proyecto Supabase NUEVO y vacío.',
  '-- No es una migración incremental: no es idempotente y asume una base vacía.',
  '--',
  '-- NO incluye (se configuran en el panel de Supabase, no en la base):',
  '--   · Ajustes de Auth: confirmación de correo desactivada, largo mínimo de',
  '--     contraseña, proveedor Google, URL del sitio y redirecciones.',
  '--   · Claves de API y secretos.',
  '--   · Los archivos del bucket de Storage (solo se declara el bucket).',
  '--   · Las cuentas de usuarios (auth.users) ni ningún dato de pacientes.',
  '--',
  '-- Los archivos numerados de sql/ cuentan la historia de cómo se llegó aquí; ante',
  '-- cualquier diferencia, ESTE archivo describe el estado real de la base.');

// Extensiones
seccion('EXTENSIONES');
for (const r of await q(`SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY 1`))
  w(`CREATE EXTENSION IF NOT EXISTS ${id(r.extname)};`);

// Tipos enumerados
const enums = await q(`SELECT t.typname, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) AS vals
  FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
  WHERE n.nspname = 'public' GROUP BY 1 ORDER BY 1`);
if (enums.length) {
  seccion('TIPOS');
  for (const e of enums) w(`CREATE TYPE public.${id(e.typname)} AS ENUM (${e.vals.map(sqlStr).join(', ')});`);
}

// Tablas
const tablas = await q(`SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r','p') ORDER BY c.relname`);
seccion('TABLAS (' + tablas.length + ')');
for (const t of tablas) {
  const cols = await q(`SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS tipo, a.attnotnull,
      pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity, a.attgenerated
    FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, [t.oid]);
  w(`CREATE TABLE IF NOT EXISTS public.${id(t.relname)} (`);
  w(cols.map(k => {
    let s = `  ${id(k.attname)} ${k.tipo}`;
    if (k.attidentity === 'a') s += ' GENERATED ALWAYS AS IDENTITY';
    else if (k.attidentity === 'd') s += ' GENERATED BY DEFAULT AS IDENTITY';
    else if (k.attgenerated === 's') s += ` GENERATED ALWAYS AS (${k.def}) STORED`;
    else if (k.def !== null) s += ' DEFAULT ' + k.def;
    if (k.attnotnull) s += ' NOT NULL';
    return s;
  }).join(',\n'));
  w(');', '');
}

// Restricciones (claves primarias/únicas/checks primero, foráneas al final)
seccion('RESTRICCIONES');
const cons = await q(`SELECT c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid) AS def
  FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid
  WHERE k.connamespace = 'public'::regnamespace AND k.contype IN ('p','u','c','f','x')
  ORDER BY CASE k.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, c.relname, k.conname`);
for (const k of cons) w(`ALTER TABLE public.${id(k.relname)} ADD CONSTRAINT ${id(k.conname)} ${k.def};`);

// Índices que no nacen de una restricción
seccion('ÍNDICES');
const nombresCons = new Set(cons.map(k => k.conname));
for (const i of await q(`SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' ORDER BY tablename, indexname`))
  if (!nombresCons.has(i.indexname)) w(i.indexdef + ';');

// RLS
seccion('SEGURIDAD A NIVEL DE FILA (RLS)');
for (const t of tablas) {
  w(t.relrowsecurity ? `ALTER TABLE public.${id(t.relname)} ENABLE ROW LEVEL SECURITY;`
                     : `-- ¡OJO! RLS DESACTIVADO en public.${t.relname}`);
  if (t.relforcerowsecurity) w(`ALTER TABLE public.${id(t.relname)} FORCE ROW LEVEL SECURITY;`);
}
const stObjRls = await q(`SELECT relrowsecurity FROM pg_class WHERE oid = 'storage.objects'::regclass`);
w(stObjRls[0]?.relrowsecurity ? '-- storage.objects: RLS activado (lo gestiona Supabase)' : '-- ¡OJO! RLS DESACTIVADO en storage.objects');

seccion('POLÍTICAS');
const pols = await q(`SELECT schemaname, tablename, policyname, permissive, array_to_string(roles, ', ') AS roles, cmd, qual, with_check
  FROM pg_policies WHERE schemaname IN ('public','storage') ORDER BY schemaname, tablename, policyname`);
for (const p of pols) {
  w(`CREATE POLICY ${id(p.policyname)} ON ${p.schemaname}.${id(p.tablename)}`
    + ` AS ${p.permissive === 'PERMISSIVE' ? 'PERMISSIVE' : 'RESTRICTIVE'} FOR ${p.cmd} TO ${p.roles || 'public'}`
    + (p.qual ? `\n  USING (${p.qual})` : '') + (p.with_check ? `\n  WITH CHECK (${p.with_check})` : '') + ';');
}

// Permisos
seccion('PERMISOS DE TABLA Y COLUMNA (anon, authenticated, service_role)');
const tp = await q(`SELECT grantee, table_name, privilege_type FROM information_schema.role_table_grants
  WHERE table_schema = 'public' AND grantee = ANY($1) ORDER BY table_name, grantee, privilege_type`, [ROLES]);
const tablaPriv = new Set(tp.map(r => `${r.grantee}|${r.table_name}|${r.privilege_type}`));
const porTabla = {};
for (const r of tp) ((porTabla[`${r.grantee}|${r.table_name}`] ||= []).push(r.privilege_type));
for (const [k, privs] of Object.entries(porTabla)) {
  const [g, t] = k.split('|');
  w(`GRANT ${privs.join(', ')} ON public.${id(t)} TO ${g};`);
}
const cp = await q(`SELECT grantee, table_name, column_name, privilege_type FROM information_schema.column_privileges
  WHERE table_schema = 'public' AND grantee = ANY($1) ORDER BY table_name, grantee, privilege_type, column_name`, [ROLES]);
const porCol = {};
for (const r of cp) {
  if (tablaPriv.has(`${r.grantee}|${r.table_name}|${r.privilege_type}`)) continue; // ya lo tiene toda la tabla
  ((porCol[`${r.grantee}|${r.table_name}|${r.privilege_type}`] ||= []).push(r.column_name));
}
if (Object.keys(porCol).length) w('', '-- Permisos solo sobre algunas columnas (el resto de columnas queda protegido):');
for (const [k, columnas] of Object.entries(porCol)) {
  const [g, t, priv] = k.split('|');
  w(`GRANT ${priv} (${columnas.map(id).join(', ')}) ON public.${id(t)} TO ${g};`);
}

// Funciones
seccion('FUNCIONES');
const fns = await q(`SELECT p.oid, p.proname, pg_get_functiondef(p.oid) AS def, p.prosecdef,
    has_function_privilege('anon', p.oid, 'EXECUTE') AS anon_ejecuta,
    has_function_privilege('authenticated', p.oid, 'EXECUTE') AS auth_ejecuta
  FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f','p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
  ORDER BY p.proname`);
for (const f of fns) {
  w(`-- ${f.proname}: ${f.prosecdef ? 'SECURITY DEFINER (corre con los permisos de su dueño)' : 'SECURITY INVOKER'}`
    + ` · anon puede ejecutarla: ${f.anon_ejecuta ? 'SÍ' : 'no'} · authenticated: ${f.auth_ejecuta ? 'sí' : 'no'}`);
  w(f.def.trimEnd() + ';', '');
}

// Disparadores
const trg = await q(`SELECT pg_get_triggerdef(t.oid) AS def FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
  WHERE c.relnamespace = 'public'::regnamespace AND NOT t.tgisinternal ORDER BY c.relname, t.tgname`);
if (trg.length) { seccion('DISPARADORES'); for (const t of trg) w(t.def + ';'); }

// Vistas
const vistas = await q(`SELECT viewname, definition FROM pg_views WHERE schemaname = 'public' ORDER BY 1`);
if (vistas.length) { seccion('VISTAS'); for (const v of vistas) w(`CREATE OR REPLACE VIEW public.${id(v.viewname)} AS\n${v.definition.trim()}`, ''); }

// Buckets (sin archivos)
seccion('STORAGE: BUCKETS (solo la configuración, sin archivos)');
for (const b of await q(`SELECT id, name, public, file_size_limit, allowed_mime_types FROM storage.buckets ORDER BY id`))
  w(`INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (${sqlStr(b.id)}, ${sqlStr(b.name)}, ${b.public}, ${b.file_size_limit ?? 'NULL'}, ${b.allowed_mime_types ? "'{" + b.allowed_mime_types.join(',') + "}'" : 'NULL'}) ON CONFLICT (id) DO NOTHING;`);

await c.end();
fs.mkdirSync(path.dirname(SALIDA), { recursive: true });
fs.writeFileSync(SALIDA, out.join('\n') + '\n');
console.log(`Listo: ${SALIDA} — ${tablas.length} tablas, ${pols.length} políticas, ${fns.length} funciones, ${cons.length} restricciones.`);
